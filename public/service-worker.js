// Service Worker for PWA functionality
const CACHE_NAME = 'cookware-store-v1';
const urlsToCache = [
  '/',
  '/index.html',
  '/manifest.json',
  '/index.css', // Assuming this is directly served or bundled
  '/Image/cookware-logo.svg',
  '/Image/cookware-icon.svg',
  '/Image/valentine-banner.png',
  '/placeholders/image-placeholder.svg',
  '/placeholders/logo-placeholder.svg',
  // Vite build output - these are general patterns and might need adjustment after a build
  '/assets/index.js', // Main bundled JS (example name)
  '/assets/index.css', // Main bundled CSS (example name)
  // More specific hashed asset patterns would be ideal, but requires build inspection.
  // For now, this greatly improves upon caching source files.
];

// Install event
self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => {
        return cache.addAll(urlsToCache);
      })
      .catch((error) => {
        console.log('Cache installation error:', error);
      })
  );
  self.skipWaiting();
});

// Activate event
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((cacheNames) => {
      return Promise.all(
        cacheNames.map((cacheName) => {
          if (cacheName !== CACHE_NAME) {
            return caches.delete(cacheName);
          }
        })
      );
    })
  );
  self.clients.claim();
});

// Fetch event - Network first, fall back to cache
self.addEventListener('fetch', (event) => {
  // Skip non-GET requests
  if (event.request.method !== 'GET') {
    return;
  }

  event.respondWith(
    fetch(event.request)
      .then((response) => {
        // Don't cache non-successful responses
        if (!response || response.status !== 200 || response.type !== 'basic') {
          return response;
        }

        // Clone the response
        const responseToCache = response.clone();

        caches.open(CACHE_NAME)
          .then((cache) => {
            cache.put(event.request, responseToCache);
          });

        return response;
      })
      .catch(() => {
        // Return cached version if network fails
        return caches.match(event.request)
          .then((response) => {
            return response || new Response('Offline - Page not cached', {
              status: 503,
              statusText: 'Service Unavailable',
              headers: new Headers({
                'Content-Type': 'text/plain'
              })
            });
          });
      })
  );
});

// Handle messages from clients
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
});
